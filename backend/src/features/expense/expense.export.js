import ExcelJS from 'exceljs';
import PDFDocument from 'pdfkit';
import moment from 'moment-timezone';
import HttpError from '../../utils/httpError.utils.js';

const TIMEZONE = 'Asia/Kolkata';
const EM_DASH = '-';

export const EXPENSE_COLUMNS = [
  { key: 'date', header: 'Date', width: 16 },
  { key: 'expenseNumber', header: 'Expense #', width: 18 },
  { key: 'name', header: 'Expense Name', width: 28 },
  { key: 'expenseType', header: 'Expense Type', width: 22 },
  { key: 'category', header: 'Category', width: 20 },
  { key: 'vendor', header: 'Vendor', width: 22 },
  { key: 'status', header: 'Status', width: 16 },
  { key: 'totalAmount', header: 'Total (INR)', width: 16 },
  { key: 'recordedPaidAmount', header: 'Paid (INR)', width: 16 },
  { key: 'outstandingAmount', header: 'Balance Due (INR)', width: 18 },
  { key: 'paymentMethod', header: 'Payment Mode', width: 16 },
  { key: 'reference', header: 'Payment Ref / UTR', width: 22 },
  { key: 'notes', header: 'Notes', width: 30 },
];

const STATUS_COLORS = {
  Paid: 'FF15803D',
  'Partially Paid': 'FFB45309',
  Unpaid: 'FFB91C1C',
};

const readable = (val) => String(val || '').replace(/_/g, ' ');

const toIstDate = (value) => moment.tz(value, TIMEZONE);

const neutralizeFormula = (value) => (/^[=+\-@\t\r]/.test(value) ? `'${value}` : value);

const csvCell = (value) => {
  if (value === null || value === undefined) return '""';
  const text = typeof value === 'number' ? String(value) : neutralizeFormula(String(value));
  return `"${text.replace(/"/g, '""')}"`;
};

export function assertFormat(format) {
  const f = String(format || 'xlsx').toLowerCase();
  if (!['csv', 'xlsx', 'pdf'].includes(f)) {
    throw new HttpError(400, 'Export format must be csv, xlsx, or pdf.');
  }
  return f;
}

export function exportFileName(format, query = {}) {
  const stamp = moment.tz(TIMEZONE).format('YYYY-MM-DD');
  const period = String(query.period || 'expenses').toLowerCase();
  const dateTag = query.startDate && query.endDate
    ? `${String(query.startDate).slice(0, 10)}_to_${String(query.endDate).slice(0, 10)}`
    : stamp;
  return `expenses_${period}_${dateTag}.${format}`;
}

export function buildExpenseReport(records = [], query = {}, meta = {}) {
  const now = moment.tz(TIMEZONE);
  const rows = records.map((r) => {
    const d = r.expenseDate ? toIstDate(r.expenseDate) : null;
    const isPaid = r.settlementStatus === 'PAID';
    const isPartial = r.settlementStatus === 'PARTIALLY_PAID';
    const statusText = isPaid ? 'Paid' : isPartial ? 'Partially Paid' : 'Unpaid';

    // Extract any completed/latest payment details
    const lastPayment = Array.isArray(r.payments) && r.payments.length > 0 ? r.payments[0] : null;

    return {
      date: d ? d.format('DD MMM YYYY') : EM_DASH,
      expenseNumber: r.expenseNumber || EM_DASH,
      name: r.name || 'Expense',
      expenseType: readable(r.expenseType) || EM_DASH,
      category: r.category || 'Uncategorized',
      vendor: r.vendor?.name ? `${r.vendor.name}${r.vendor.upiId ? ` (${r.vendor.upiId})` : ''}` : EM_DASH,
      status: statusText,
      totalAmount: Number((r.totalAmount || 0).toFixed(2)),
      recordedPaidAmount: Number((r.recordedPaidAmount || 0).toFixed(2)),
      outstandingAmount: Number((r.outstandingAmount || 0).toFixed(2)),
      paymentMethod: lastPayment?.paymentMethod || (isPaid ? 'PAID' : EM_DASH),
      reference: lastPayment?.transactionReference || lastPayment?.externalTransactionReference || EM_DASH,
      notes: r.description || r.notes || '',
    };
  });

  const totalSpend = rows.reduce((acc, r) => acc + (r.totalAmount || 0), 0);
  const totalPaid = rows.reduce((acc, r) => acc + (r.recordedPaidAmount || 0), 0);
  const totalOutstanding = rows.reduce((acc, r) => acc + (r.outstandingAmount || 0), 0);

  // Friendly names for active filters shown in report header
  const periodLabel = query.period ? readable(query.period).toUpperCase() : 'ALL TIME';
  const dateRangeLabel = query.startDate && query.endDate
    ? `${String(query.startDate).slice(0, 10)} to ${String(query.endDate).slice(0, 10)}`
    : query.startDate
    ? `From ${String(query.startDate).slice(0, 10)}`
    : 'All Time';
  const statusFilterLabel = query.settlementStatus ? readable(query.settlementStatus) : 'All Statuses';
  const categoryFilterLabel = query.category ? query.category : 'All Categories';
  const typeFilterLabel = query.expenseType ? readable(query.expenseType) : 'All Types';
  const searchFilterLabel = query.search ? `"${query.search}"` : 'None';

  const summary = [
    ['Report Title', 'Community Expense Report'],
    ['Generated On', now.format('DD MMM YYYY, hh:mm A z')],
    ['Generated By', meta.generatedBy || 'Community Administrator'],
    ['Active Filter: Period', periodLabel],
    ['Active Filter: Date Range', dateRangeLabel],
    ['Active Filter: Status', statusFilterLabel],
    ['Active Filter: Category', categoryFilterLabel],
    ['Active Filter: Expense Type', typeFilterLabel],
    ['Active Filter: Search', searchFilterLabel],
    ['Total Records Exported', rows.length],
    ['Total Expenses (INR)', totalSpend.toFixed(2)],
    ['Total Recorded Paid (INR)', totalPaid.toFixed(2)],
    ['Total Outstanding Due (INR)', totalOutstanding.toFixed(2)],
  ];

  return { rows, summary, totalSpend, totalPaid, totalOutstanding, query };
}

// ---------------- CSV ----------------
export function reportToCsv(report) {
  // Metadata / Active Filter parameters in header
  const metaHeaderLines = [
    '# ========================================================',
    '# COMMUNITY EXPENSE REPORT',
    '# ========================================================',
    ...report.summary.map(([label, val]) => `# ${label}: ${val}`),
    '# ========================================================',
    '',
  ];

  const header = EXPENSE_COLUMNS.map((c) => csvCell(c.header)).join(',');
  const lines = report.rows.map((row) =>
    EXPENSE_COLUMNS.map((c) => csvCell(row[c.key])).join(',')
  );

  return `\uFEFF${metaHeaderLines.join('\r\n')}${header}\r\n${lines.join('\r\n')}\r\n`;
}

// ---------------- Excel ----------------
const HEADER_FILL = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF1F3A5F' } };
const HEADER_FONT = { bold: true, color: { argb: 'FFFFFFFF' } };
const BORDER = { style: 'thin', color: { argb: 'FFD1D5DB' } };

function styleHeader(row) {
  row.eachCell((cell) => {
    cell.fill = HEADER_FILL;
    cell.font = HEADER_FONT;
    cell.alignment = { vertical: 'middle', horizontal: 'left', wrapText: true };
    cell.border = { top: BORDER, bottom: BORDER, left: BORDER, right: BORDER };
  });
  row.height = 24;
}

export async function reportToXlsxBuffer(report) {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'Nahom';
  workbook.created = new Date();

  // Sheet 1: Filter Parameters & Summary
  const summarySheet = workbook.addWorksheet('Summary');
  summarySheet.columns = [{ width: 32 }, { width: 50 }];
  report.summary.forEach(([label, value], i) => {
    const row = summarySheet.addRow([label, value]);
    if (i === 0) {
      summarySheet.mergeCells('A1:B1');
      row.getCell(1).value = String(value);
      row.getCell(1).font = { bold: true, size: 16, color: { argb: 'FF1F3A5F' } };
      row.height = 28;
    } else {
      row.getCell(1).font = { bold: true };
      row.getCell(2).alignment = { horizontal: 'left', wrapText: true };
    }
  });

  // Sheet 2: Itemized Expenses
  const sheet = workbook.addWorksheet('Expenses', { views: [{ state: 'frozen', ySplit: 1 }] });
  sheet.columns = EXPENSE_COLUMNS.map((c) => ({ header: c.header, key: c.key, width: c.width }));
  styleHeader(sheet.getRow(1));

  const statusColIndex = EXPENSE_COLUMNS.findIndex((c) => c.key === 'status') + 1;
  report.rows.forEach((r, i) => {
    const row = sheet.addRow(EXPENSE_COLUMNS.map((c) => r[c.key]));
    row.alignment = { vertical: 'middle' };
    if (i % 2 === 1) {
      row.eachCell((cell) => {
        cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFF9FAFB' } };
      });
    }
    const statusCell = row.getCell(statusColIndex);
    statusCell.font = { bold: true, color: { argb: STATUS_COLORS[r.status] || 'FF111827' } };
  });

  // Number format currency columns
  ['totalAmount', 'recordedPaidAmount', 'outstandingAmount'].forEach((colKey) => {
    const col = sheet.getColumn(colKey);
    col.numFmt = '#,##0.00';
    col.alignment = { horizontal: 'right' };
  });

  sheet.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: EXPENSE_COLUMNS.length } };

  return Buffer.from(await workbook.xlsx.writeBuffer());
}

// ---------------- PDF ----------------
export function reportToPdfBuffer(report) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', layout: 'landscape', margin: 28 });
    const chunks = [];
    doc.on('data', (chunk) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    const columns = [
      ['Date', 'date', 64],
      ['Expense #', 'expenseNumber', 72],
      ['Name', 'name', 140],
      ['Category', 'category', 90],
      ['Vendor', 'vendor', 100],
      ['Status', 'status', 64],
      ['Total (INR)', 'totalAmount', 76],
      ['Paid (INR)', 'recordedPaidAmount', 70],
      ['Due (INR)', 'outstandingAmount', 70],
    ];

    const drawHeader = () => {
      doc.font('Helvetica-Bold').fontSize(14).fillColor('#1F3A5F').text('Community Expense Report');
      doc.font('Helvetica').fontSize(8).fillColor('#4B5563').text(
        `Period: ${report.summary?.[3]?.[1] || 'ALL TIME'}  |  Date: ${report.summary?.[4]?.[1] || 'All dates'}  |  Status: ${report.summary?.[5]?.[1] || 'All'}`
      );
      doc.moveDown(0.6);

      let x = 28;
      const headerY = doc.y;
      doc.font('Helvetica-Bold').fontSize(7.5).fillColor('#FFFFFF');
      columns.forEach(([header, , width]) => {
        doc.rect(x, headerY, width, 18).fill('#1F3A5F');
        doc.fillColor('#FFFFFF').text(header, x + 3, headerY + 5, { width: width - 6, lineBreak: false });
        x += width;
      });
      doc.y = headerY + 22;
    };

    const drawRow = (row, index) => {
      const y = doc.y;
      const rowHeight = 20;
      if (y + rowHeight > doc.page.height - 35) {
        doc.addPage();
        drawHeader();
        return drawRow(row, index);
      }
      let x = 28;
      if (index % 2 === 1) {
        doc.rect(28, y - 1, 746, rowHeight).fill('#F9FAFB');
      }
      doc.font('Helvetica').fontSize(7).fillColor('#111827');
      columns.forEach(([, key, width]) => {
        const val = row[key];
        const text = typeof val === 'number' ? val.toLocaleString('en-IN', { minimumFractionDigits: 2 }) : String(val ?? EM_DASH);
        doc.text(text, x + 3, y + 4, { width: width - 6, height: 14, ellipsis: true });
        x += width;
      });
      doc.y = y + rowHeight;
    };

    drawHeader();
    report.rows.forEach(drawRow);

    if (!report.rows.length) {
      doc.font('Helvetica').fontSize(10).fillColor('#4B5563').text('No expenses match the selected filters.');
    } else {
      // Summary footer
      doc.moveDown(1);
      doc.font('Helvetica-Bold').fontSize(8).fillColor('#1F3A5F').text(
        `Totals:  Expenses: INR ${report.totalSpend.toFixed(2)}  |  Paid: INR ${report.totalPaid.toFixed(2)}  |  Outstanding: INR ${report.totalOutstanding.toFixed(2)}  (${report.rows.length} records)`
      );
    }

    doc.end();
  });
}
