import multer from 'multer';
import path from 'path';
import fs from 'fs';
import crypto from 'crypto';
import { fileURLToPath } from 'url';
import HttpError from '../../utils/httpError.utils.js';
import { verifyMagicBytesSync, cleanUploadedFiles } from '../../utils/storage.utils.js';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../..');
const uploadDir = path.resolve(root, 'public/uploads/expenses');
if (!fs.existsSync(uploadDir)) fs.mkdirSync(uploadDir, { recursive: true });
const storage = multer.diskStorage({ destination: uploadDir, filename: (req, file, cb) => cb(null, `expense-${crypto.randomBytes(16).toString('hex')}${path.extname(file.originalname).toLowerCase()}`) });
const fileFilter = (req, file, cb) => { const allowed = ['.jpg', '.jpeg', '.png', '.webp', '.pdf']; const ext = path.extname(file.originalname).toLowerCase(); if (!allowed.includes(ext) || !['image/jpeg', 'image/png', 'image/webp', 'application/pdf'].includes(file.mimetype)) return cb(new HttpError(400, 'Only JPG, PNG, WEBP, and PDF files are allowed.')); cb(null, true); };
export const expenseUpload = multer({ storage, fileFilter, limits: { fileSize: 10 * 1024 * 1024, files: 1 } });
export const expenseFileSignatureValidator = (req, res, next) => { if (!req.file || !verifyMagicBytesSync(req.file.path, ['IMAGE', 'PDF'])) { cleanUploadedFiles(req); return next(new HttpError(400, 'Invalid attachment file signature.')); } next(); };
export { uploadDir };
