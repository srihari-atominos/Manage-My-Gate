import mongoose from 'mongoose';
import { METHODS, OCR_STATUSES, SETTLEMENT_STATUSES, TYPES } from './personalExpense.constants.js';

const schema = new mongoose.Schema({
  orgId: { type: mongoose.Schema.Types.ObjectId, ref: 'Organization', required: true, index: true },
  userId: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true, index: true },
  type: { type: String, enum: TYPES, required: true },
  amountMinor: { type: Number, required: true, min: 1, validate: Number.isSafeInteger },
  currency: { type: String, enum: ['INR'], default: 'INR', immutable: true },
  categoryId: { type: String, required: true, trim: true, maxlength: 64 },
  categoryName: { type: String, required: true, trim: true, maxlength: 80 },
  transactionDate: { type: String, required: true, match: /^\d{4}-\d{2}-\d{2}$/ },
  paymentMethod: { type: String, enum: METHODS, required: true },
  paymentSettlement: { type: String, enum: SETTLEMENT_STATUSES, required: true, default: 'UNPAID' },
  merchantOrSource: { type: String, default: '', trim: true, maxlength: 160 },
  merchantNormalized: { type: String, default: '', trim: true, maxlength: 160 },
  notes: { type: String, default: '', trim: true, maxlength: 1000 },
  reference: { type: String, default: null, trim: true, maxlength: 128 },
  receipt: {
    storageName: { type: String, select: false },
    originalName: { type: String },
    mimeType: { type: String },
    size: { type: Number },
    uploadedAt: { type: Date },
    ocrStatus: { type: String, enum: OCR_STATUSES },
    ocrEngineStatus: { type: String, maxlength: 64 },
    ocrError: { type: String, maxlength: 240 },
    ocr: {
      merchant: String,
      merchantAddress: String,
      receiptNumber: String,
      invoiceNumber: String,
      billNumber: String,
      transactionId: String,
      orderId: String,
      documentType: String,
      receiptDate: String,
      currency: String,
      subtotalMinor: Number,
      taxMinor: Number,
      discountMinor: Number,
      additionalChargesMinor: Number,
      totalMinor: Number,
      totalAmount: Number,
      items: [{
        description: String,
        quantity: Number,
        unitPriceMinor: Number,
        amountMinor: Number,
        confidence: Number,
      }],
      confidence: Number,
      fieldConfidence: mongoose.Schema.Types.Mixed,
      warnings: [{
        code: String,
        message: String,
        field: String,
        candidates: mongoose.Schema.Types.Mixed,
      }],
      ocrEngine: String,
      mode: String,
      disagreements: [{
        field: String,
        message: String,
        tesseractValue: mongoose.Schema.Types.Mixed,
        oxrValue: mongoose.Schema.Types.Mixed,
      }],
      provenance: mongoose.Schema.Types.Mixed,
      documentDisplayedStatus: String,
      verifiedPaymentStatus: { type: String, default: 'UNVERIFIED' },
      isPaymentScreenshot: Boolean,
      paymentMethod: String,
      transactionReference: String,
      needsReview: Boolean,
      settlement: String,
      paymentApplication: String,
      payeeUpiId: String,
      receiptTime: String,
      expenseDate: String,
      cgstMinor: Number,
      sgstMinor: Number,
      subtotalAmount: Number,
      suggestedExpenseName: String,
      suggestedCategory: String,
      suggestedExpenseType: String,
      suggestedNotes: String,
      notes: String,
      description: String,
      singleEngineFallback: String,
      providerStatuses: mongoose.Schema.Types.Mixed,
      confirmedAt: Date,
    },
  },
  source: { type: String, enum: ['MANUAL'], default: 'MANUAL' },
  isDeleted: { type: Boolean, default: false },
  deletedAt: { type: Date, default: null },
}, { timestamps: true });

schema.index({ orgId: 1, userId: 1, transactionDate: -1, createdAt: -1 });
schema.index({ orgId: 1, userId: 1, categoryId: 1, transactionDate: -1 });
schema.index({ orgId: 1, userId: 1, reference: 1 }, { unique: true, partialFilterExpression: { reference: { $type: 'string' } } });

export default mongoose.model('PersonalExpenseTransaction', schema);
