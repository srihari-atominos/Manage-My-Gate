import { Router } from 'express';
import isAuthenticated from '../../middlewares/auth.middleware.js';
import tenantContext from '../../middlewares/tenant.middleware.js';
import { authorizeResidentSelfService } from '../../middlewares/rbac.middleware.js';
import { validate } from '../../middlewares/validator.middleware.js';
import controller from './personalExpense.controller.js';
import { budgetRules, categoryRules, createTransactionRules, idRules, listRules, periodQueryRules, receiptReviewRules, updateTransactionRules } from './personalExpense.validator.js';
import { receiptSignatureValidator, receiptUpload } from './personalExpenseUpload.middleware.js';

const router = Router();
router.use(isAuthenticated, tenantContext, authorizeResidentSelfService());
router.get('/dashboard', validate(periodQueryRules), controller.dashboard);
router.get('/categories', controller.categories);
router.post('/categories', validate(categoryRules), controller.createCategory);
router.delete('/categories/:id', validate(idRules), controller.removeCategory);
router.get('/budgets', validate(periodQueryRules), controller.budgets);
router.put('/budgets', validate(budgetRules), controller.saveBudget);
router.delete('/budgets', validate(periodQueryRules), controller.removeBudget);
router.get('/transactions', validate(listRules), controller.list);
router.post('/transactions', validate(createTransactionRules), controller.create);
router.post('/transactions/:id/receipt', validate(idRules), receiptUpload.single('receipt'), receiptSignatureValidator, controller.uploadReceipt);
router.post('/transactions/:id/receipt/ocr', validate(idRules), controller.retryReceipt);
router.patch('/transactions/:id/receipt', validate(receiptReviewRules), controller.updateReceipt);
router.delete('/transactions/:id/receipt', validate(idRules), controller.removeReceipt);
router.get('/transactions/:id/receipt/file', validate(idRules), controller.receiptFile);
router.get('/transactions/:id', validate(idRules), controller.get);
router.patch('/transactions/:id', validate(updateTransactionRules), controller.update);
router.delete('/transactions/:id', validate(idRules), controller.remove);
export default router;