type Listener = () => void;
const listeners = new Set<Listener>();

let currentLanguageCode: LanguageCode = 'en';

export const i18n = {
  getCurrentLanguage: (): LanguageCode => currentLanguageCode,

  subscribe: (listener: Listener): (() => void) => {
    listeners.add(listener);
    return () => listeners.delete(listener);
  },

  setLanguage: async (code: LanguageCode): Promise<void> => {
    currentLanguageCode = code;
    try {
      await storage.setItem('language_preference', code);
    } catch (e) {
      console.warn('Failed to save language preference:', e);
    }
    listeners.forEach((cb) => cb());
  },

  initLanguage: async (): Promise<LanguageCode> => {
    try {
      const saved = await storage.getItem('language_preference');
      if (saved && (saved === 'en' || saved === 'ta' || saved === 'hi' || saved === 'ml' || saved === 'kn')) {
        currentLanguageCode = saved as LanguageCode;
      }
    } catch (e) {
      console.warn('Failed to init language preference:', e);
    }
    listeners.forEach((cb) => cb());
    return currentLanguageCode;
  },

  t: (key: string, fallback?: string): string => {
    const dict = TRANSLATIONS[currentLanguageCode] || TRANSLATIONS.en;
    return dict[key] || fallback || TRANSLATIONS.en[key] || key;
  },

  tCategoryName: (key?: string, fallback?: string): string => {
    if (!key) return fallback || '';
    const dictKey = `category_${key}`;
    return i18n.t(dictKey, fallback);
  },

  tFeatureName: (id?: string, fallback?: string): string => {
    if (!id) return fallback || '';
    const dictKey = `feature_${id}_name`;
    return i18n.t(dictKey, fallback);
  },

  tFeatureSubtitle: (id?: string, fallback?: string): string => {
    if (!id) return fallback || '';
    const dictKey = `feature_${id}_sub`;
    return i18n.t(dictKey, fallback);
  },

  tRole: (roleName?: string, fallback?: string): string => {
    if (!roleName) return fallback || '';
    const raw = String(roleName).trim();
    const normalizedKey = `role_${raw.toLowerCase().replace(/[\s\/-]+/g, '_')}`;
    return i18n.t(normalizedKey, fallback || raw);
  },
};

export const useTranslation = () => {
  const [lang, setLang] = useState<LanguageCode>(currentLanguageCode);

  useEffect(() => {
    setLang(i18n.getCurrentLanguage());
    const unsubscribe = i18n.subscribe(() => {
      setLang(i18n.getCurrentLanguage());
    });
    return unsubscribe;
  }, []);

  return {
    t: i18n.t,
    tCategoryName: i18n.tCategoryName,
    tFeatureName: i18n.tFeatureName,
    tFeatureSubtitle: i18n.tFeatureSubtitle,
    tRole: i18n.tRole,
    languageCode: lang,
    setLanguage: i18n.setLanguage,
  };
};

export default i18n;
