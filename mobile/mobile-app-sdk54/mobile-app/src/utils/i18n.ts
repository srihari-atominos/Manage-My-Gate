let currentLanguageCode: LanguageCode = 'en';
const listeners = new Set<(lang: LanguageCode) => void>();

export const i18n = {
  getCurrentLanguage: (): LanguageCode => currentLanguageCode,

  subscribe: (fn: (lang: LanguageCode) => void): (() => void) => {
    listeners.add(fn);
    return () => listeners.delete(fn);
  },

  setLanguage: async (code: LanguageCode): Promise<void> => {
    currentLanguageCode = code;
    try {
      await storage.setItem('language_preference', code);
    } catch (e) {
      console.warn('Failed to save language preference:', e);
    }
    listeners.forEach((fn) => fn(code));
  },

  initLanguage: async (): Promise<LanguageCode> => {
    try {
      const saved = await storage.getItem('language_preference');
      if (
        saved &&
        (saved === 'en' || saved === 'ta' || saved === 'hi' || saved === 'ml' || saved === 'te' || saved === 'kn')
      ) {
        currentLanguageCode = saved as LanguageCode;
      }
    } catch (e) {
      console.warn('Failed to init language preference:', e);
    }
    return currentLanguageCode;
  },

  t: (key: string, fallback?: string): string => {
    const dict = TRANSLATIONS[currentLanguageCode] || TRANSLATIONS.en;
    return dict[key] || fallback || TRANSLATIONS.en[key] || key;
  },

  /**
   * Translates text dynamically to active language while strictly preserving:
   * 1. Numbers (e.g. 104, 24, 7, 02/09/2026, 18:00)
   * 2. Currency, symbols, punctuation (e.g. ₹, $, #, @, %, -, +, :, /)
   * 3. Codes & technical identifiers (e.g. #G-4982, v1.0.0)
   */
  translateText: (rawText: string): string => {
    if (!rawText || typeof rawText !== 'string' || currentLanguageCode === 'en') {
      return rawText;
    }

    const trimmed = rawText.trim();
    if (!trimmed) return rawText;

    // Check exact dictionary match by key or normalized text
    const dict = TRANSLATIONS[currentLanguageCode];
    if (dict) {
      const normalizedKey = trimmed.toLowerCase().replace(/[^a-z0-9]+/g, '_');
      if (dict[normalizedKey]) {
        return rawText.replace(trimmed, dict[normalizedKey]);
      }
      for (const [k, enVal] of Object.entries(TRANSLATIONS.en)) {
        if (enVal.toLowerCase() === trimmed.toLowerCase() && dict[k]) {
          return rawText.replace(trimmed, dict[k]);
        }
      }
    }

    // Word token replacement preserving numbers & special characters
    const wordDict = WORD_MAP[currentLanguageCode];
    if (!wordDict) return rawText;

    return rawText.replace(/\b([a-zA-Z]+)\b/g, (match) => {
      const lower = match.toLowerCase();
      if (wordDict[lower]) {
        return wordDict[lower];
      }
      return match;
    });
  },
};

export default i18n;
